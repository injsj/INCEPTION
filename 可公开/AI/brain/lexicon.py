def load():
    """种子词典 + 管理员已批准的扩展词（lexicon_extra.json）。"""
    words = seed()
    if EXTRA_FILE.exists():
        try:
            for item in json.loads(EXTRA_FILE.read_text(encoding="utf-8")):
                if item.get("词") and item["词"] not in words:
                    words[item["词"]] = {"词性": item.get("词性", "待补"),
                                         "释义": item.get("释义", "待补")}
        except ValueError:
            pass   # 扩展文件损坏则只用种子，不影响主流程
    return words



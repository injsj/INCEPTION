GRAMMAR_EXTRA_FILE = config.STATE / "lexicon_grammar_extra.json"


def grammar_full():
    """语法词典 = 种子 + 已批准扩展（lexicon_grammar_extra.json，管理员批准后写入）。
    这就是「新动词只登记词典、句子自动长出」的正式登记通道。"""
    g = grammar()
    if GRAMMAR_EXTRA_FILE.exists():
        try:
            for item in json.loads(GRAMMAR_EXTRA_FILE.read_text(encoding="utf-8")):
                if item.get("词"):
                    g[item["词"]] = {k: v for k, v in item.items() if k != "词"}
        except ValueError:
            pass   # 扩展文件损坏则只用种子，不影响主流程
    return g



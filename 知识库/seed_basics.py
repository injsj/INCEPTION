def main():
    for name, prefix in TYPES:
        ok, msg = store.add_type(name, prefix)
        print(("新建类型" if ok else "类型已在") + "：{} ({})".format(name, prefix))

    existing = {info["title"] for info in store._index().values()}
    made, skipped = 0, 0
    for tname, title, summary, usage, exp, limit, content in E:
        if title in existing:
            skipped += 1
            continue
        entry, msg = store.create_entry("trusted", tname, {
            "title": title, "summary": summary, "usage": usage,
            "experience": exp, "limitations": limit, "content": content,
        })
        if entry is None:
            print("失败：{} —— {}".format(title, msg))
        else:
            made += 1
    print("播种完成：新增 {} 条，跳过已存在 {} 条".format(made, skipped))
    print("当前计数：", store.counts())


if __name__ == "__main__":
    main()

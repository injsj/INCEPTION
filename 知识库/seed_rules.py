def main():
    existing = {info["title"] for info in store._index().values()}
    n_new, n_skip = 0, 0
    for title, summary, usage, exp, lim, content in E:
        if title in existing:
            n_skip += 1
            continue
        entry, msg = store.create_entry("trusted", TYPE, {
            "title": title, "summary": summary, "usage": usage,
            "experience": exp, "limitations": lim, "content": content,
        })
        if entry is None:
            print("失败：{} —— {}".format(title, msg))
        else:
            n_new += 1
            print("  +", entry["id"], title)
    print("播种完成：新增 {} 条，跳过（已存在）{} 条".format(n_new, n_skip))
    print("当前计数：", store.counts())


if __name__ == "__main__":
    main()

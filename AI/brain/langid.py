"""语言识别：字符集规则（规格书第 1 节）。
不用惊动知识库——看字符范围即可，微秒级完成。"""

RANGES = [
    ("zh", 0x4E00, 0x9FFF), ("zh", 0x3400, 0x4DBF),   # 汉字
    ("ja", 0x3040, 0x30FF),                            # 假名
    ("ko", 0xAC00, 0xD7AF), ("ko", 0x1100, 0x11FF),    # 谚文
    ("ru", 0x0400, 0x04FF),                            # 西里尔
    ("ar", 0x0600, 0x06FF),                            # 阿拉伯
]


def detect(text):
    """返回文本中首个出现的"特征文字"语言；拉丁字母只在没有任何
    特征文字时兜底为英语（修复："P1讲了什么"这类标记开头的中文句被误判为 en）。"""
    latin = False
    for ch in text:
        o = ord(ch)
        for lang, lo, hi in RANGES:
            if lo <= o <= hi:
                return lang
        if ch.isalpha():
            latin = True   # 先记下，继续找后面的汉字/假名等特征文字
    return "en" if latin else "unknown"
